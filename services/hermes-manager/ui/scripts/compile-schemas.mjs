import { createHash } from "node:crypto";
import { format } from "prettier";
import Ajv07 from "ajv";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const registry = [];
const schemaMetadata = {};
const check = process.argv.includes("--check");
const dir = "src/schemas/generated";
mkdirSync(dir, { recursive: true });
const schemaDirectory = "../../../contracts/hermes-manager/schemas";
for (const [name, file] of [
  ["template", "template-v2.json"],
  ["backend", "terminal-backend-v1.json"],
  ["managed", "hermes-managed-v1.json"],
]) {
  const schema = JSON.parse(readFileSync(`${schemaDirectory}/${file}`, "utf8"));
  registry.push({
    id: schema.$id,
    revision: schema["x-revision"],
    digest: createHash("sha256")
      .update(readFileSync(`${schemaDirectory}/${file}`))
      .digest("hex"),
    compatibleImageDigests: schema["x-compatibleImageDigests"] ?? [],
  });
  schemaMetadata[name] = schema;
  // Each schema declares its draft; the managed Hermes schema is draft-07.
  const Ajv = schema.$schema?.includes("2020-12") ? Ajv2020 : Ajv07;
  const ajv = new Ajv({
    allErrors: true,
    strict: false,
    validateFormats: false,
    coerceTypes: false,
    useDefaults: false,
    code: { source: true, esm: true },
  });
  const imports = new Set();
  const compiled = standaloneCode(ajv, ajv.compile(schema)).replace(
    /require\("ajv\/dist\/runtime\/([a-zA-Z0-9]+)"\)\.default/g,
    (_match, name) => {
      imports.add(name);
      return `runtime_${name}`;
    },
  );
  if (compiled.includes("require("))
    throw new Error("Unexpected standalone runtime dependency");
  const source =
    "// Generated by scripts/compile-schemas.mjs; do not edit.\n" +
    [...imports]
      .sort()
      .map(
        (name) =>
          `import module_${name} from "ajv/dist/runtime/${name}.js";\nconst runtime_${name}=module_${name}.default ?? module_${name};\n`,
      )
      .join("") +
    compiled +
    "\n";
  const declaration =
    'import type { ValidateFunction } from "ajv";\ndeclare const validate: ValidateFunction;\nexport default validate;\n';
  for (const [path, content] of [
    [`${dir}/${name}.js`, source],
    [`${dir}/${name}.d.ts`, declaration],
  ]) {
    if (check) {
      if (readFileSync(path, "utf8") !== content)
        throw new Error(`Stale schema validator: ${path}`);
    } else writeFileSync(path, content);
  }
}

const extra = [
  [
    `${dir}/metadata.ts`,
    await format(
      `// Generated by scripts/compile-schemas.mjs; do not edit.\nexport const registry=${JSON.stringify(registry)} as const;\nexport const schemas=${JSON.stringify(schemaMetadata)} as const;\n`,
      { parser: "typescript" },
    ),
  ],
];
for (const [path, content] of extra) {
  if (check) {
    if (readFileSync(path, "utf8") !== content)
      throw new Error(`Stale schema registry: ${path}`);
  } else writeFileSync(path, content);
}
